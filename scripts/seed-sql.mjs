// Prints SQL that loads the demo data (seed/demo.ts) into an empty database.
// Usage: node scripts/seed-sql.mjs > supabase/seed.sql
import { demo } from "../seed/demo.ts";

const q = v => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  if (Array.isArray(v)) return `array[${v.map(q).join(", ")}]::text[]`;
  if (typeof v === "object") return `${q(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const insert = (table, rows, map) => {
  const cols = Object.keys(map(rows[0]));
  return `insert into public.${table} (${cols.join(", ")}) values\n${rows.map(r => `  (${Object.values(map(r)).map(q).join(", ")})`).join(",\n")}\non conflict (id) do nothing;\n`;
};

console.log("-- Demo data. Generated by scripts/seed-sql.mjs from seed/demo.ts. Do not edit by hand.\n");
console.log(insert("staff", demo.staff, s => ({ id: s.id, name: s.name, email: s.email, role: s.role, active: s.active })));
console.log(insert("services", demo.services, s => s));
console.log(insert("customers", demo.customers, c => c));
console.log(insert("bookings", demo.bookings, b => ({
  id: b.id, customer_id: b.customer_id, service_id: b.service_id, staff_id: b.staff_id,
  date: b.date, start_time: b.start, end_time: b.end, status: b.status, price_cents: b.price_cents
})));
console.log(insert("payments", demo.payments, p => p));
